namespace CP.Localisation.Generators;

using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;
using System.Xml;
using System.Xml.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

/// <summary>Generates statically registered string resource providers.</summary>
[Generator(LanguageNames.CSharp)]
public sealed class ResxGenerator : IIncrementalGenerator
{
    private static readonly DiagnosticDescriptor InvalidResource = new(
        "LOCGEN001",
        "Invalid resource file",
        "Cannot generate resources for '{0}': {1}",
        "Localisation",
        DiagnosticSeverity.Error,
        true);

    private static readonly DiagnosticDescriptor ObjectResource = new(
        "LOCGEN002",
        "Object resource needs a provider",
        "Resource '{0}' in '{1}' is not a string; register an explicit provider for Native AOT, or use legacy resource lookup",
        "Localisation",
        DiagnosticSeverity.Warning,
        true);

    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var inputs = context.AdditionalTextsProvider
            .Where(static file => file.Path.EndsWith(".resx", StringComparison.OrdinalIgnoreCase))
            .Combine(context.AnalyzerConfigOptionsProvider)
            .Select(static (pair, cancellation) =>
            {
                var options = pair.Right.GetOptions(pair.Left);
                _ = options.TryGetValue("build_metadata.AdditionalFiles.LocalisationResourceName", out var name);
                _ = options.TryGetValue("build_metadata.AdditionalFiles.CultureName", out var culture);
                return new ResourceInput(
                    pair.Left.Path,
                    name ?? string.Empty,
                    culture ?? string.Empty,
                    pair.Left.GetText(cancellation)?.ToString() ?? string.Empty);
            }).WithTrackingName("ResxInputs");
        var settings = context.AnalyzerConfigOptionsProvider.Select(static (options, cancellation) =>
        {
            _ = options.GlobalOptions.TryGetValue("build_property.AssemblyName", out var assembly);
            _ = options.GlobalOptions.TryGetValue("build_property.NeutralLanguage", out var neutral);
            return new Settings(assembly ?? "Resources", neutral ?? string.Empty);
        });
        var needsModuleInitializer = context.CompilationProvider.Select(static (compilation, _) =>
            compilation.GetTypeByMetadataName("System.Runtime.CompilerServices.ModuleInitializerAttribute") is null);
        context.RegisterSourceOutput(needsModuleInitializer, static (output, needed) =>
        {
            if (!needed)
            {
                return;
            }

            output.AddSource(
                "Localisation.ModuleInitializerAttribute.g.cs",
                "// <auto-generated/>\nnamespace System.Runtime.CompilerServices { " +
                "[global::System.AttributeUsage(global::System.AttributeTargets.Method)] " +
                "internal sealed class ModuleInitializerAttribute : global::System.Attribute { } }");
        });
        context.RegisterSourceOutput(inputs.Collect().Combine(settings), static (output, pair) => Emit(output, pair.Left, pair.Right));
    }

    private static void Emit(SourceProductionContext output, ImmutableArray<ResourceInput> inputs, Settings settings)
    {
        if (settings.Neutral.Length > 0)
        {
            try
            {
                _ = CultureInfo.GetCultureInfo(settings.Neutral);
            }
            catch (CultureNotFoundException exception)
            {
                output.ReportDiagnostic(Diagnostic.Create(InvalidResource, Location.None, "NeutralLanguage", exception.Message));
                return;
            }
        }

        var dictionaries = new SortedDictionary<string, SortedDictionary<string, SortedDictionary<string, string>>>(StringComparer.Ordinal);
        foreach (var input in inputs)
        {
            output.CancellationToken.ThrowIfCancellationRequested();
            ReadInput(output, dictionaries, input);
        }

        if (dictionaries.Count == 0)
        {
            return;
        }

        var source = new StringBuilder(
            "// <auto-generated/>\n#nullable enable\n" +
            "namespace CP.Localisation.Generated { internal static class ResourceModule {\n" +
            "[global::System.Runtime.CompilerServices.ModuleInitializerAttribute] internal static void Initialize() {\n");
        var index = 0;
        foreach (var dictionary in dictionaries)
        {
            var cultures = dictionary.Value.Keys.Where(static value => value.Length > 0)
                .Concat(settings.Neutral.Length == 0 ? Array.Empty<string>() : new[] { settings.Neutral })
                .Distinct(StringComparer.OrdinalIgnoreCase);
            _ = source
                .Append("global::CP.Localisation.LocalisationResourceRegistry.Register(")
                .Append(Literal(settings.Assembly))
                .Append(',')
                .Append(Literal(dictionary.Key))
                .Append(", Get")
                .Append(index)
                .Append(", new string[] {")
                .Append(string.Join(",", cultures.Select(Literal)))
                .Append("});\n");
            index++;
        }

        _ = source.Append("}\n");
        AppendProviders(source, dictionaries, settings);
        _ = source.Append("} }\n");
        output.AddSource("Localisation.ResourceModule.g.cs", SourceText.From(source.ToString(), Encoding.UTF8));
    }

    private static void AppendProviders(
        StringBuilder source,
        SortedDictionary<string, SortedDictionary<string, SortedDictionary<string, string>>> dictionaries,
        Settings settings)
    {
        const string providerDeclaration = "private static object? Get";
        var index = 0;
        foreach (var dictionary in dictionaries)
        {
            _ = source
                .Append(providerDeclaration)
                .Append(index)
                .Append("(string key, global::System.Globalization.CultureInfo culture) { while (true) {\n")
                .Append("if (global::System.String.Equals(culture.Name, ")
                .Append(Literal(settings.Neutral))
                .Append(", global::System.StringComparison.OrdinalIgnoreCase)) break;\n");
            var cultureIndex = 0;
            foreach (var culture in dictionary.Value.Where(static pair => pair.Key.Length > 0))
            {
                _ = source.Append("if (global::System.String.Equals(culture.Name, ")
                    .Append(Literal(culture.Key))
                    .Append(", global::System.StringComparison.OrdinalIgnoreCase)) { var value = Get")
                    .Append(index).Append("Culture").Append(cultureIndex)
                    .Append("(key); if (value is not null) return value; }\n");
                cultureIndex++;
            }

            _ = source.Append("if (culture.Name.Length == 0) break; culture = culture.Parent; } return Get")
                .Append(index).Append("Neutral(key); }\n");
            cultureIndex = 0;
            foreach (var culture in dictionary.Value.Where(static pair => pair.Key.Length > 0))
            {
                _ = source.Append(providerDeclaration).Append(index).Append("Culture").Append(cultureIndex)
                    .Append("(string key) { switch (key) {\n");
                AppendValues(source, culture.Value);
                _ = source.Append("default: return null; } }\n");
                cultureIndex++;
            }

            _ = source.Append(providerDeclaration).Append(index).Append("Neutral(string key) { switch (key) {\n");
            if (dictionary.Value.TryGetValue(string.Empty, out var neutral))
            {
                AppendValues(source, neutral);
            }

            _ = source.Append("default: return null; } }\n");
            index++;
        }
    }

    private static void ReadInput(
        SourceProductionContext output,
        SortedDictionary<string, SortedDictionary<string, SortedDictionary<string, string>>> dictionaries,
        ResourceInput input)
    {
        try
        {
            var culture = input.Culture;
            var name = input.Name;
            if (string.IsNullOrEmpty(name))
            {
                throw new InvalidDataException("Resource base name metadata is missing; import Localisation.Generators.targets.");
            }

            if (culture.Length > 0)
            {
                _ = CultureInfo.GetCultureInfo(culture);
                if (name.EndsWith($".{culture}", StringComparison.OrdinalIgnoreCase))
                {
                    name = name.Substring(0, name.Length - culture.Length - 1);
                }
            }

            if (!dictionaries.TryGetValue(name, out var cultures))
            {
                cultures = new(StringComparer.OrdinalIgnoreCase);
                dictionaries.Add(name, cultures);
            }

            if (!cultures.TryGetValue(culture, out var values))
            {
                values = new(StringComparer.Ordinal);
                cultures.Add(culture, values);
            }

            ReadValues(output, input, values);
        }
        catch (Exception exception) when (exception is XmlException || exception is InvalidDataException || exception is ArgumentException)
        {
            output.ReportDiagnostic(Diagnostic.Create(InvalidResource, Location.None, input.Path, exception.Message));
        }
    }

    private static void ReadValues(SourceProductionContext output, ResourceInput input, SortedDictionary<string, string> values)
    {
        using var reader = XmlReader.Create(
            new StringReader(input.Text),
            new XmlReaderSettings { DtdProcessing = DtdProcessing.Prohibit, XmlResolver = null });
        var document = XDocument.Load(reader);
        foreach (var data in document.Root?.Elements("data") ?? Enumerable.Empty<XElement>())
        {
            output.CancellationToken.ThrowIfCancellationRequested();
            const string NameAttribute = "name";
            var key = (string?)data.Attribute(NameAttribute) ?? throw new InvalidDataException("A resource has no name.");
            var type = (string?)data.Attribute("type");
            if (data.Attribute("mimetype") is not null ||
                (type?.Split(',')[0].Trim().Equals("System.String", StringComparison.Ordinal) == false))
            {
                output.ReportDiagnostic(Diagnostic.Create(ObjectResource, Location.None, key, input.Path));
                continue;
            }

            values.Add(key, data.Element("value")?.Value ?? string.Empty);
        }
    }

    private static void AppendValues(StringBuilder source, SortedDictionary<string, string> values)
    {
        foreach (var value in values)
        {
            _ = source.Append("case ").Append(Literal(value.Key)).Append(": return ").Append(Literal(value.Value)).Append(";\n");
        }
    }

    private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, true);

    private sealed record ResourceInput(string Path, string Name, string Culture, string Text);

    private sealed record Settings(string Assembly, string Neutral);
}
